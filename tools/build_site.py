BASE = 'https://tasbihdigitalcounter.netlify.app'   # replace with your custom domain (see README)
E = lambda s: html.escape(s, quote=True)
def W(name, text):
    with open(os.path.join(ROOT, name), 'w', encoding='utf-8') as f: f.write(text)
def R(name):
    with open(os.path.join(ROOT, name), encoding='utf-8') as f: return f.read()

LANGS = ['en', 'ar', 'ur', 'id', 'tr']
LPATH = {'en': '/', 'ar': '/ar', 'ur': '/ur', 'id': '/id', 'tr': '/tr'}

# ---------- i18n.js ----------
def build_i18n():
    data = {'groups': GROUP_ORDER, 'presets': [list(p) for p in PRESETS], 'm': MEANINGS, 'ui': UI}
    W('i18n.js', '/* Generated by tools/build_site.py - do not edit by hand. */\nwindow.TDC_I18N=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')

# ---------- shared markup ----------
def hreflang_links():
    out = ''.join(f'<link rel="alternate" hreflang="{l}" href="{BASE}{LPATH[l] if LPATH[l]!="/" else "/"}"/>' for l in LANGS)
    return out + f'<link rel="alternate" hreflang="x-default" href="{BASE}/"/>'

def lang_switcher(cur, label='Language'):
    items = []
    for l in LANGS:
        name = UI[l]['langName']
        if l == cur: items.append(f'<strong lang="{l}">{E(name)}</strong>')
        else: items.append(f'<a href="{LPATH[l]}" hreflang="{l}" lang="{l}">{E(name)}</a>')
    return f'<nav class="lang-switch" aria-label="{label}">' + ' · '.join(items) + '</nav>'

